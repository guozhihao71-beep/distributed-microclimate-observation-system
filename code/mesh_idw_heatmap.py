import numpy as np
import pandas as pd
import time
import os
from datetime import datetime


# ============================================================
# 1. 设置数据保存路径
# ============================================================
# raw_file_path 用于保存原始数据，包括接收到的数据和丢包数据
# processed_file_path 用于保存经过清洗、异常值处理和平滑后的数据
# os.path.expanduser("~") 表示当前用户目录
# Desktop 表示把 CSV 文件保存到桌面
raw_file_path = os.path.join(os.path.expanduser("~"), "Desktop", "mesh_realtime_raw.csv")
processed_file_path = os.path.join(os.path.expanduser("~"), "Desktop", "mesh_realtime_processed.csv")


# ============================================================
# 2. 设置传感器节点信息
# ============================================================
# nodes 表示系统中的多个分布式传感节点
# 每个节点包含：
# node_id：节点编号
# x, y：节点在农田/果园中的空间位置坐标
# offset：该节点的局部温度偏移量，对应公式中的 ΔT_node
#
# offset 的意义：
# Node_A offset = -3.0，表示该点位比平均环境更冷，可能代表低洼区域
# Node_B offset = -1.0，表示该点位略低于平均温度
# Node_C offset = 1.0，表示该点位略高于平均温度
# Node_D offset = 2.5，表示该点位较暖，可能代表通风较好或地势较高区域
nodes = [
    {"node_id": "Node_A", "x": 0,  "y": 0,  "offset": -3.0},
    {"node_id": "Node_B", "x": 10, "y": 0,  "offset": -1.0},
    {"node_id": "Node_C", "x": 0,  "y": 10, "offset": 1.0},
    {"node_id": "Node_D", "x": 10, "y": 10, "offset": 2.5},
]


# ============================================================
# 3. 设置主节点 / 网关编号
# ============================================================
# gateway_id 表示所有子节点最终都会把数据发送到这个中心网关
# 在你的系统设计中，这个网关可以理解为 Raspberry Pi 主节点
gateway_id = "Gateway_1"


# ============================================================
# 4. 创建空列表，用于持续保存所有采集到的数据
# ============================================================
# data 是一个总数据列表
# 每一次循环产生的新数据都会 append 到这个列表中
# 最后再转换成 Pandas DataFrame 并保存成 CSV 文件
data = []


# ============================================================
# 5. 启动提示
# ============================================================
# 程序会一直运行，模拟实时传感器系统
# 如果想停止程序，在终端中按 Ctrl + C
print("Mesh system started with data processing... Press Ctrl+C to stop")


# ============================================================
# 6. 主循环：持续模拟数据采集、通信、存储和处理
# ============================================================
while True:

    # ------------------------------------------------------------
    # 6.1 获取当前时间
    # ------------------------------------------------------------
    # timestamp 是当前完整时间，例如：2026-05-05 06:30:00
    # hour 是当前小时的小数形式，例如：
    # 6:30 会表示为 6.5
    # 14:15 会表示为 14.25
    #
    # hour 对应温度公式中的 t
    # 即 T(t) 里的 t
    timestamp = datetime.now()
    hour = timestamp.hour + timestamp.minute / 60


    # ============================================================
    # 7. 温度模拟模型
    # ============================================================
    # 本项目采用以下温度模型：
    #
    # T(t) = T_mean + A * sin((2π / 24) * (t - phi)) + ΔT_node + ε
    #
    # 其中：
    # T(t)        ：当前时刻的模拟温度
    # T_mean      ：日平均温度
    # A           ：温度振幅，表示一天中温度上下波动的幅度
    # t           ：当前时间，单位为小时
    # phi         ：相位偏移，用于控制温度曲线的时间位置
    # ΔT_node     ：不同节点的局部温度偏移
    # ε           ：随机扰动，用于模拟传感器误差和自然环境波动
    #
    # 使用 sin 函数的原因：
    # 真实空气温度通常具有明显的昼夜周期变化：
    # 夜间温度下降，白天温度升高，整体趋势接近周期曲线。
    # 因此，用 sin/cos 函数可以合理模拟日温度变化趋势。
    # ============================================================

    # ------------------------------------------------------------
    # 7.1 设置日平均温度 T_mean
    # ------------------------------------------------------------
    # T_mean 对应公式中的 T_mean
    # 这里设置为 8°C，表示一天中的平均环境温度大约为 8°C
    # 如果想模拟更冷的霜冻夜晚，可以改成 5 或 6
    # 如果想模拟较暖天气，可以改成 10 或 12
    T_mean = 8


    # ------------------------------------------------------------
    # 7.2 设置温度振幅 A
    # ------------------------------------------------------------
    # A 对应公式中的 A
    # 这里设置为 6°C，表示温度围绕平均值上下波动约 6°C
    # 例如：
    # 平均温度 8°C，振幅 6°C
    # 理论上温度可能大约在 2°C 到 14°C 之间变化
    A = 6


    # ------------------------------------------------------------
    # 7.3 设置相位偏移 phi
    # ------------------------------------------------------------
    # phi 对应公式中的 φ
    # 它控制一天中最低温和最高温出现的时间
    #
    # 这里设置 phi = 6
    # 代表温度曲线以早上 6 点附近作为一个关键相位点
    # 这样可以模拟日出前后较低温、白天逐渐升温的趋势
    #
    # 你也可以根据实际情况调整：
    # phi = 5：最低温更接近凌晨 5 点
    # phi = 6：最低温更接近清晨 6 点
    # phi = 7：最低温更接近日出后
    phi = 6


    # ------------------------------------------------------------
    # 7.4 计算日周期温度项
    # ------------------------------------------------------------
    # 这一项对应公式中的：
    # A * sin((2π / 24) * (t - phi))
    #
    # 2π 表示一个完整周期
    # 24 表示一天 24 小时
    # hour 表示当前时间 t
    # phi 表示相位偏移
    #
    # daily_temperature_cycle 只表示“昼夜周期变化部分”
    # 还没有加入平均温度、节点偏移和随机扰动
    daily_temperature_cycle = A * np.sin((2 * np.pi / 24) * (hour - phi))


    # ------------------------------------------------------------
    # 7.5 计算基础温度部分
    # ------------------------------------------------------------
    # base_temp 对应：
    # T_mean + A * sin((2π / 24) * (t - phi))
    #
    # 注意：
    # 这里还没有加入 ΔT_node 和 ε
    # 因为不同节点的 offset 和 noise 要在 for node in nodes 循环中分别加入
    base_temp = T_mean + daily_temperature_cycle


    # ============================================================
    # 8. 湿度模拟模型
    # ============================================================
    # 湿度通常与温度呈一定反向关系：
    # 温度升高时，相对湿度往往下降；
    # 温度降低时，相对湿度往往升高。
    #
    # 所以这里使用与温度相反方向的 sin 函数来模拟湿度变化。
    # 这不是精确气象模型，而是用于系统验证的合理近似。
    # ============================================================

    # hum_cycle 表示湿度的日变化部分
    # 负号表示湿度变化趋势与温度相反
    hum_cycle = -10 * np.sin((2 * np.pi / 24) * (hour - phi))

    # base_hum 表示基础湿度
    # 65 是平均相对湿度
    # hum_cycle 是日周期变化
    base_hum = 65 + hum_cycle


    # ============================================================
    # 9. 气压模拟模型
    # ============================================================
    # 气压变化通常比温度和湿度更小
    # 这里设置一个较小的周期变化，用于模拟自然环境中的轻微气压波动
    # ============================================================

    # pres_cycle 表示气压的周期变化
    # 2 表示气压波动幅度较小
    # hour - 3 表示气压变化相位与温度略有不同
    pres_cycle = 2 * np.sin((2 * np.pi / 24) * (hour - 3))

    # base_pres 表示基础气压
    # 1010 hPa 是一个常见近似大气压数值
    base_pres = 1010 + pres_cycle


    # ============================================================
    # 10. 遍历每一个传感器节点，分别生成数据
    # ============================================================
    for node in nodes:

        # ------------------------------------------------------------
        # 10.1 生成温度随机扰动 ε
        # ------------------------------------------------------------
        # epsilon 对应公式中的 ε
        # np.random.normal(0, 0.4) 表示生成均值为 0、标准差为 0.4 的随机噪声
        #
        # 这个噪声用于模拟：
        # 1. 传感器测量误差
        # 2. 短时间环境波动
        # 3. 微小随机扰动
        epsilon = np.random.normal(0, 0.4)


        # ------------------------------------------------------------
        # 10.2 计算节点温度
        # ------------------------------------------------------------
        # 这里正式使用完整公式：
        #
        # T(t) = T_mean + A * sin((2π / 24) * (t - phi)) + ΔT_node + ε
        #
        # 在代码中：
        # base_temp      = T_mean + A * sin((2π / 24) * (hour - phi))
        # node["offset"] = ΔT_node
        # epsilon        = ε
        #
        # 所以：
        # temperature = base_temp + node["offset"] + epsilon
        #
        # 这样每一个节点都会有：
        # 1. 相同的日变化趋势
        # 2. 不同的局部温度偏移
        # 3. 不同的随机扰动
        temperature = base_temp + node["offset"] + epsilon


        # ------------------------------------------------------------
        # 10.3 生成湿度随机噪声
        # ------------------------------------------------------------
        # hum_noise 表示湿度传感器误差或短时湿度波动
        # 均值为 0，标准差为 1.5
        hum_noise = np.random.normal(0, 1.5)


        # ------------------------------------------------------------
        # 10.4 生成气压随机噪声
        # ------------------------------------------------------------
        # pres_noise 表示气压传感器误差或短时气压波动
        # 均值为 0，标准差为 0.3
        pres_noise = np.random.normal(0, 0.3)


        # ------------------------------------------------------------
        # 10.5 计算湿度和气压
        # ------------------------------------------------------------
        # humidity = 基础湿度 + 随机噪声
        # pressure = 基础气压 + 随机噪声
        humidity = base_hum + hum_noise
        pressure = base_pres + pres_noise


        # ------------------------------------------------------------
        # 10.6 限制湿度范围
        # ------------------------------------------------------------
        # 相对湿度理论范围是 0% 到 100%
        # 所以这里用 max 和 min 限制湿度范围
        #
        # 如果 humidity 小于 0，则设为 0
        # 如果 humidity 大于 100，则设为 100
        humidity = max(0, min(100, humidity))


        # ============================================================
        # 11. 模拟 Mesh 网络通信性能
        # ============================================================

        # ------------------------------------------------------------
        # 11.1 模拟丢包
        # ------------------------------------------------------------
        # np.random.random() 会生成 0 到 1 之间的随机数
        # 如果该随机数小于 0.03，则认为该数据包丢失
        #
        # 0.03 表示 3% 的丢包率
        packet_loss = np.random.random() < 0.03


        # ------------------------------------------------------------
        # 11.2 模拟通信延迟
        # ------------------------------------------------------------
        # delay_ms 表示数据从子节点发送到网关的延迟
        # np.random.randint(20, 180) 表示随机生成 20 到 180 ms 的延迟
        delay_ms = np.random.randint(20, 180)


        # ============================================================
        # 12. 根据是否丢包生成数据记录
        # ============================================================

        # ------------------------------------------------------------
        # 12.1 如果没有丢包，则保存真实模拟数据
        # ------------------------------------------------------------
        if not packet_loss:

            # record 表示一条完整的数据记录
            # 每条记录包含：
            # 时间戳、节点编号、位置、温度、湿度、气压、网关编号、网络类型、延迟、状态
            record = [
                timestamp.strftime("%Y-%m-%d %H:%M:%S"),  # 当前时间
                node["node_id"],                         # 节点编号
                node["x"],                               # 节点 x 坐标
                node["y"],                               # 节点 y 坐标
                round(temperature, 2),                   # 温度，保留两位小数
                round(humidity, 2),                      # 湿度，保留两位小数
                round(pressure, 2),                      # 气压，保留两位小数
                gateway_id,                              # 网关编号
                "Mesh",                                  # 网络类型
                delay_ms,                                # 通信延迟
                "Received"                               # 数据接收状态
            ]

            # 在终端打印当前成功接收到的数据
            print(record)

        # ------------------------------------------------------------
        # 12.2 如果发生丢包，则温度、湿度和气压记为 NaN
        # ------------------------------------------------------------
        else:

            # 丢包情况下，环境数据无法被网关接收
            # 所以 temperature、humidity、pressure 用 np.nan 表示缺失值
            record = [
                timestamp.strftime("%Y-%m-%d %H:%M:%S"),  # 当前时间
                node["node_id"],                         # 节点编号
                node["x"],                               # 节点 x 坐标
                node["y"],                               # 节点 y 坐标
                np.nan,                                  # 温度缺失
                np.nan,                                  # 湿度缺失
                np.nan,                                  # 气压缺失
                gateway_id,                              # 网关编号
                "Mesh",                                  # 网络类型
                delay_ms,                                # 通信延迟
                "Lost"                                   # 数据丢失状态
            ]

            # 在终端提示哪个节点发生丢包
            print("Packet lost from", node["node_id"])


        # ------------------------------------------------------------
        # 12.3 将当前记录加入总数据列表
        # ------------------------------------------------------------
        data.append(record)


    # ============================================================
    # 13. 保存原始数据
    # ============================================================

    # 将 data 列表转换成 Pandas DataFrame
    # DataFrame 相当于 Python 中的表格数据结构
    df_raw = pd.DataFrame(data, columns=[
        "timestamp", "node_id", "x", "y",
        "temperature", "humidity", "pressure",
        "gateway", "network",
        "delay_ms", "status"
    ])

    # 将原始数据保存到 CSV 文件
    # 原始数据包括 Received 和 Lost 两种状态
    df_raw.to_csv(raw_file_path, index=False)


    # ============================================================
    # 14. 数据处理部分
    # ============================================================

    # ------------------------------------------------------------
    # 14.1 删除丢包数据
    # ------------------------------------------------------------
    # 只保留 status 为 Received 的数据
    # 因为 Lost 数据没有有效的温度、湿度和气压
    df_processed = df_raw[df_raw["status"] == "Received"].copy()


    # ------------------------------------------------------------
    # 14.2 删除空值
    # ------------------------------------------------------------
    # 删除 temperature、humidity、pressure 中存在 NaN 的行
    df_processed = df_processed.dropna(subset=["temperature", "humidity", "pressure"])


    # ------------------------------------------------------------
    # 14.3 按节点分别进行异常值检测
    # ------------------------------------------------------------
    # cleaned_list 用于保存每个节点清洗后的数据
    cleaned_list = []

    # groupby("node_id") 表示按照节点编号分组
    # 这样可以避免把不同节点的数据混在一起判断异常值
    for node_id, group in df_processed.groupby("node_id"):

        # 复制当前节点的数据，避免直接修改原始数据
        group_cleaned = group.copy()

        # 对温度、湿度和气压分别进行 IQR 异常值检测
        for col in ["temperature", "humidity", "pressure"]:

            # Q1 是第一四分位数，也就是 25% 位置的数据
            Q1 = group_cleaned[col].quantile(0.25)

            # Q3 是第三四分位数，也就是 75% 位置的数据
            Q3 = group_cleaned[col].quantile(0.75)

            # IQR 是四分位距，表示中间 50% 数据的范围
            IQR = Q3 - Q1

           
            lower_bound = Q1 - 1.5 * IQR               # # 正常范围下界
            upper_bound = Q3 + 1.5 * IQR                ## # 正常范围上界

            # 只保留处于正常范围内的数据
            group_cleaned = group_cleaned[
                (group_cleaned[col] >= lower_bound) &
                (group_cleaned[col] <= upper_bound)
            ]

        # 将当前节点清洗后的数据加入列表
        cleaned_list.append(group_cleaned)


    # ============================================================
    # 15. 如果存在清洗后的数据，则继续进行平滑处理
    # ============================================================
    if cleaned_list:

        # 将所有节点清洗后的数据重新合并为一个 DataFrame
        df_processed = pd.concat(cleaned_list)


        # ------------------------------------------------------------
        # 15.1 转换时间格式
        # ------------------------------------------------------------
        # 将 timestamp 从字符串转换为 datetime 类型
        # 这样后面可以按照时间排序和绘图
        df_processed["timestamp"] = pd.to_datetime(df_processed["timestamp"])


        # ------------------------------------------------------------
        # 15.2 按节点和时间排序
        # ------------------------------------------------------------
        # 先按 node_id 排序，再按 timestamp 排序
        # 保证每个节点的数据都按照时间顺序排列
        df_processed = df_processed.sort_values(["node_id", "timestamp"])


        # ------------------------------------------------------------
        # 15.3 温度移动平均平滑
        # ------------------------------------------------------------
        # rolling(window=5) 表示使用最近 5 个数据点计算平均值
        # min_periods=1 表示即使不足 5 个数据点，也可以计算平均值
        #
        # 这样可以减少随机噪声，使温度变化曲线更平滑
        df_processed["temperature_smooth"] = (
            df_processed
            .groupby("node_id")["temperature"]
            .transform(lambda x: x.rolling(window=5, min_periods=1).mean())
        )


        # ------------------------------------------------------------
        # 15.4 湿度移动平均平滑
        # ------------------------------------------------------------
        df_processed["humidity_smooth"] = (
            df_processed
            .groupby("node_id")["humidity"]
            .transform(lambda x: x.rolling(window=5, min_periods=1).mean())
        )


        # ------------------------------------------------------------
        # 15.5 气压移动平均平滑
        # ------------------------------------------------------------
        df_processed["pressure_smooth"] = (
            df_processed
            .groupby("node_id")["pressure"]
            .transform(lambda x: x.rolling(window=5, min_periods=1).mean())
        )


        # ------------------------------------------------------------
        # 15.6 增加霜冻风险判断
        # ------------------------------------------------------------
        # 如果平滑后的温度小于等于 2°C，则判断为 Frost Risk
        # 否则判断为 Normal
        #
        # 这里使用 temperature_smooth，而不是原始 temperature
        # 是因为平滑后的温度更稳定，不容易被单个随机噪声影响
        df_processed["frost_status"] = np.where(
            df_processed["temperature_smooth"] <= 2,
            "Frost Risk",
            "Normal"
        )


        # ------------------------------------------------------------
        # 15.7 保存处理后的数据
        # ------------------------------------------------------------
        df_processed.to_csv(processed_file_path, index=False)


    # ============================================================
    # 16. 打印文件保存位置
    # ============================================================
    print("Raw data saved to:", raw_file_path)
    print("Processed data saved to:", processed_file_path)


    # ============================================================
    # 17. 设置采样间隔
    # ============================================================
    # 程序每 5 秒生成一次数据
    # 在真实系统中，这可以理解为模拟每 5 分钟采样一次
    #
    # 如果你想让数据生成更快，可以改成 time.sleep(1)
    # 如果你想更接近真实环境监测，可以改成 time.sleep(300)
    time.sleep(5)